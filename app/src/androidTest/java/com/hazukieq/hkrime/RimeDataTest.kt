package com.hazukieq.hkrime

import android.util.Log
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.hazukieq.hkrime.core.Rime
import com.hazukieq.hkrime.data.AppPrefs
import com.hazukieq.hkrime.data.Config
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File

/**
 * 设备端部署与 OpenCC 功能验证。
 *
 * 覆盖点：
 * 1. 首次启动部署：assets/rime 下所有文件（含恢复的 15 个 opencc *.txt 与后续整合的客家话方案/词典）
 *    被复制到 sharedDataDir（/sdcard/Android/data/<pkg>/files/rime）；
 * 2. OpenCC 词典转换：Rime.get(context, true) -> OpenCCDictManager.internalDeploy()
 *    把 assets 里的 *.txt 转成 librime / OpenCC 需要的 *.ocd2；
 * 3. OpenCC 实际转换：Rime.openccConvert() 用 s2t.json / t2s.json 逐行验证简繁互转；
 * 4. 方案可部署：build/ 下生成 hakka_jiugong 对应的 *.bin。
 *
 * 运行：./gradlew connectedDebugAndroidTest
 */
@RunWith(AndroidJUnit4::class)
class RimeDataTest {

    private val tag = "RimeDataTest"

    @Test
    fun deployAndOpenccWorks() {
        val inst = InstrumentationRegistry.getInstrumentation()
        val ctx = inst.targetContext

        // 实际数据目录来自 AppPrefs（默认 /storage/emulated/0/rime），不是 getExternalFilesDir
        val conf = AppPrefs.defaultInstance().conf
        val sharedDir = File(conf.sharedDataDir)   // assets 部署目标
        val userDir = File(conf.userDataDir)       // librime build/ 与 userdb 目标
        Log.i(tag, "sharedDataDir=$sharedDir")

        // 强制一次全新部署：清空 app 专属的 sharedDataDir 与 librime build 缓存，
        // 否则同版本覆盖安装时 Config.prepareRime() 不会重新拷贝 assets（isOverwrite=false）。
        // 注意：本测试是破坏性的，userDataDir(/sdcard/rime) 请先备份或改用测试机。
        sharedDir.deleteRecursively()
        File(userDir, "build").deleteRecursively()

        // Config 构造器内部即 prepareRime()（首次会 copy assets 并 full deploy），主线程执行
        inst.runOnMainSync { Config.get(ctx) }
        Log.i(tag, "after Config: opencc entries=" +
            (File(sharedDir, "opencc").list()?.size ?: -1) + " ocd2=" +
            (File(sharedDir, "opencc").list()?.count { it.endsWith(".ocd2") } ?: -1))

        // 无论是否是首次，强制一次完整部署：Rime.destroy() 后以 full_check=true 重新初始化，
        // 这会调用 OpenCCDictManager.internalDeploy()（把 opencc/*.txt 转成 *.ocd2）再部署 librime。
        inst.runOnMainSync {
            Rime.destroy()
            Rime.get(ctx, true)
        }
        Log.i(tag, "after force deploy: ocd2=" +
            (File(sharedDir, "opencc").list()?.count { it.endsWith(".ocd2") } ?: -1))

        // 1) 基础资源
        assertTrue("trime.yaml not deployed", File(sharedDir, "trime.yaml").exists())
        assertTrue("default.custom.yaml missing", File(sharedDir, "default.custom.yaml").exists())
        // 2) 客家话方案 / 词典（来自 rime.zip）
        assertTrue("hakka_jiugong.schema.yaml not deployed",
            File(sharedDir, "hakka_jiugong.schema.yaml").exists())
        assertTrue("hakka.dict.yaml not deployed", File(sharedDir, "hakka.dict.yaml").exists())
        assertTrue("hakka_oftenwords.dict.yaml not deployed",
            File(sharedDir, "hakka_oftenwords.dict.yaml").exists())
        // 3) OpenCC 资源 + txt->ocd2 转换
        val openccDir = File(sharedDir, "opencc")
        assertTrue("opencc dir missing", openccDir.isDirectory)
        assertTrue("opencc/s2t.json missing", File(openccDir, "s2t.json").exists())
        assertTrue("opencc/STCharacters.txt missing", File(openccDir, "STCharacters.txt").exists())
        val ocd2 = openccDir.listFiles()?.filter { it.name.endsWith(".ocd2") } ?: emptyList()
        Log.i(tag, "opencc ocd2 count=${ocd2.size}: ${ocd2.map { it.name }}")
        assertTrue("no *.ocd2 generated by OpenCCDictManager.internalDeploy()", ocd2.size >= 17)
        assertTrue("STCharacters.ocd2 missing", File(openccDir, "STCharacters.ocd2").exists())

        // 4) librime 部署产物（注意：build/ 在 userDataDir，不在 sharedDataDir）
        val buildDir = File(userDir, "build")
        val bins = buildDir.listFiles()?.filter { it.name.endsWith(".bin") } ?: emptyList()
        Log.i(tag, "build bins=${bins.size}: ${bins.map { it.name }.take(20)}")
        assertTrue("librime deploy produced no *.bin", bins.isNotEmpty())
        assertTrue("hakka dict tables were not built",
            bins.any { it.name == "hakka.table.bin" })

        // 5) OpenCC 版本 + 实际转换
        val version = Rime.get_opencc_version()
        Log.i(tag, "opencc version=$version")
        assertTrue("opencc version empty", !version.isNullOrEmpty())

        val s2t = Rime.openccConvert("汉字", "s2t.json")
        Log.i(tag, "s2t(\u6c49\u5b57)=$s2t")
        assertEquals("s2t conversion wrong", "漢字", s2t)

        val t2s = Rime.openccConvert("漢字", "t2s.json")
        Log.i(tag, "t2s(\u6f22\u5b57)=$t2s")
        assertEquals("t2s conversion wrong", "汉字", t2s)

        val s2tw = Rime.openccConvert("软件", "s2tw.json")
        Log.i(tag, "s2tw(\u8f6f\u4ef6)=$s2tw")
        assertEquals("s2tw conversion wrong", "軟件", s2tw)

        val s2twp = Rime.openccConvert("软件", "s2twp.json")
        Log.i(tag, "s2twp(\u8f6f\u4ef6)=$s2twp")
        assertEquals("s2twp conversion wrong", "軟體", s2twp)

        val schemas = Rime.getSchemaNames()
        Log.i(tag, "schema list=${schemas?.toList()}")
        assertTrue("no schema loaded", !schemas.isNullOrEmpty())

        // 6) schema_list 里列的三个方案都必须真实存在并可部署
        val schemaNames = schemas?.toList() ?: emptyList()
        assertTrue("客语12键 missing from schema list: $schemaNames",
            schemaNames.any { it.contains("客语12键") })
        assertTrue("客语26键 missing from schema list: $schemaNames",
            schemaNames.any { it.contains("客语26键") })
        assertTrue("雲龍國際音標 missing from schema list: $schemaNames",
            schemaNames.any { it.contains("雲龍") })
        // 26 键方案与 IPA 方案的部署产物
        assertTrue("hakka_qwerty.prism.bin missing", File(buildDir, "hakka_qwerty.prism.bin").exists())
        assertTrue("ipa_yunlong.prism.bin missing", File(buildDir, "ipa_yunlong.prism.bin").exists())
        assertTrue("luna_pinyin reverse_lookup dict was not built",
            bins.any { it.name.startsWith("luna_pinyin") })

        // 7) ywz（颜文字/表情）与 lenth（网络/方言词联想）两个 OpenCC 滤镜
        //    说明：OpenCC 一个词条可以有多个值（text 词典里用空格分隔），
        //    librime 的 simplifier 会把 Values() 全部作为候选展示（见 librime
        //    src/rime/gear/simplifier.cc: Opencc::ConvertWord）。
        //    Rime.openccConvert() 走的是 OpenCC SimpleConverter，只取第一个值，
        //    因此这里只能验证「配置可加载、转换不崩溃」，词条多值语义由
        //    script/verify-rime-assets.py 静态校验。
        assertTrue("ywz.ocd2 missing after deploy", File(openccDir, "ywz.ocd2").exists())
        assertTrue("lenth.ocd2 missing after deploy", File(openccDir, "lenth.ocd2").exists())
        val ywz = Rime.openccConvert("不屑", "ywz.json")
        Log.i(tag, "ywz(不屑)=$ywz")
        assertTrue("ywz.json failed to load (conversion returned null)", ywz != null)
        val lenth = Rime.openccConvert("qq", "lenth.json")
        Log.i(tag, "lenth(qq)=$lenth")
        assertTrue("lenth.json failed to load (conversion returned null)", lenth != null)
    }


}
